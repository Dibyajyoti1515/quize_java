package com.quiztrack.model;

import java.io.Serializable;
import java.sql.Timestamp;

/**
 * Data Transfer Object representing an individual proctoring or telemetry event in a student's audit trail.
 */
public class ProctorActivityEventDto implements Serializable {
    private static final long serialVersionUID = 1L;

    private int logId;
    private int attemptId;
    private int studentId;
    private String studentName;
    private String studentIdentifier;
    private String eventType; // 'TAB_SWITCH', 'FULLSCREEN_EXIT', 'FOCUS_LOST', 'INACTIVITY', 'HEARTBEAT', etc.
    private String severity;  // 'INFO', 'CAUTION', 'CRITICAL'
    private String details;
    private Timestamp eventTimestamp;
    private String timestampFormatted;

    // Teacher Review Status
    private boolean isReviewed;
    private Integer reviewedBy;
    private String reviewerName;
    private Timestamp reviewedAt;
    private String reviewNotes;

    public ProctorActivityEventDto() {
        this.severity = "INFO";
        this.isReviewed = false;
    }

    public int getLogId() {
        return logId;
    }

    public void setLogId(int logId) {
        this.logId = logId;
    }

    public int getAttemptId() {
        return attemptId;
    }

    public void setAttemptId(int attemptId) {
        this.attemptId = attemptId;
    }

    public int getStudentId() {
        return studentId;
    }

    public void setStudentId(int studentId) {
        this.studentId = studentId;
    }

    public String getStudentName() {
        return studentName;
    }

    public void setStudentName(String studentName) {
        this.studentName = studentName;
    }

    public String getStudentIdentifier() {
        return studentIdentifier;
    }

    public void setStudentIdentifier(String studentIdentifier) {
        this.studentIdentifier = studentIdentifier;
    }

    public String getEventType() {
        return eventType;
    }

    public void setEventType(String eventType) {
        this.eventType = eventType;
    }

    public String getSeverity() {
        return severity;
    }

    public void setSeverity(String severity) {
        this.severity = severity;
    }

    public String getDetails() {
        return details;
    }

    public void setDetails(String details) {
        this.details = details;
    }

    public Timestamp getEventTimestamp() {
        return eventTimestamp;
    }

    public void setEventTimestamp(Timestamp eventTimestamp) {
        this.eventTimestamp = eventTimestamp;
    }

    public String getTimestampFormatted() {
        return timestampFormatted;
    }

    public void setTimestampFormatted(String timestampFormatted) {
        this.timestampFormatted = timestampFormatted;
    }

    public boolean isReviewed() {
        return isReviewed;
    }

    public void setReviewed(boolean reviewed) {
        isReviewed = reviewed;
    }

    public Integer getReviewedBy() {
        return reviewedBy;
    }

    public void setReviewedBy(Integer reviewedBy) {
        this.reviewedBy = reviewedBy;
    }

    public String getReviewerName() {
        return reviewerName;
    }

    public void setReviewerName(String reviewerName) {
        this.reviewerName = reviewerName;
    }

    public Timestamp getReviewedAt() {
        return reviewedAt;
    }

    public void setReviewedAt(Timestamp reviewedAt) {
        this.reviewedAt = reviewedAt;
    }

    public String getReviewNotes() {
        return reviewNotes;
    }

    public void setReviewNotes(String reviewNotes) {
        this.reviewNotes = reviewNotes;
    }
}
